import AppKit
import NoMessCore
import os

/// Decisions only, never clipboard contents:
///   log stream --predicate 'subsystem == "dev.noky.nomess"'
private let log = Logger(subsystem: "dev.noky.nomess", category: "pasteboard")

/// Polls the general pasteboard and rewrites terminal copies that contain
/// hard-wrapped lines or diagrams.
@MainActor
final class PasteboardWatcher {
    /// Markers from nspasteboard.org that password managers and similar tools
    /// put on content that must not be inspected or kept.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// What we last wrote for a copy containing diagrams, so the pasteboard
    /// can follow the app the user switches to.
    private struct DiagramCopy {
        let plain: String
        let fenced: String
        let html: String
        let notesHTML: String
        var variant: DiagramVariant
        var changeCount: Int

        /// Plain text and HTML to put on the pasteboard for `variant`.
        func contents(for variant: DiagramVariant) -> (string: String, html: String) {
            switch variant {
            case .original: (plain, html)
            case .notes: (plain, notesHTML)
            case .fenced: (fenced, html)
            }
        }
    }

    /// Real glyph widths of the fonts diagrams end up in: Menlo, which our
    /// HTML asks for, and the SF Mono of Notes' monostyled blocks.
    private let menloMetrics = CoreTextMetrics.menlo()
    private let notesMetrics = CoreTextMetrics(font: NSFont.monospacedSystemFont(ofSize: 12, weight: .regular) as CTFont)

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var activationObserver: NSObjectProtocol?
    private var diagramCopy: DiagramCopy?

    init() {
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        // Skip whatever was copied while we were off.
        lastChangeCount = pasteboard.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.3, repeats: true) { _ in
            MainActor.assumeIsolated { self.poll() }
        }
        activationObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { [weak self] note in
            let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
            let bundleIdentifier = app?.bundleIdentifier
            MainActor.assumeIsolated { self?.adapt(to: bundleIdentifier) }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        if let activationObserver {
            NSWorkspace.shared.notificationCenter.removeObserver(activationObserver)
        }
        activationObserver = nil
        diagramCopy = nil
    }

    private func poll() {
        // Reading changeCount does not read the contents.
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        diagramCopy = nil

        // Only look inside the pasteboard when the copy came from a terminal.
        let frontmost = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        guard TerminalApps.contains(frontmost) else {
            log.info("change \(changeCount): skipped, frontmost \(frontmost ?? "nil", privacy: .public) is not a terminal")
            return
        }

        let types = Set(pasteboard.types ?? [])
        let typeNames = types.map(\.rawValue).sorted().joined(separator: ", ")
        guard types.isDisjoint(with: Self.ignoredTypes) else {
            log.info("change \(changeCount): skipped, marked types [\(typeNames, privacy: .public)]")
            return
        }

        guard let text = pasteboard.string(forType: .string) else {
            log.info("change \(changeCount): skipped, no plain text in [\(typeNames, privacy: .public)]")
            return
        }
        let cleaned = HardWrapCleaner.clean(text)
        let realigned = DiagramDetector.restoringClippedFirstLine(cleaned ?? text)
        let result = realigned ?? cleaned ?? text
        let diagramBlocks = DiagramDetector.blocks(result)
        log.info("change \(changeCount) from \(frontmost ?? "nil", privacy: .public) [\(typeNames, privacy: .public)]: unwrapped \(cleaned != nil), realigned \(realigned != nil), diagrams \(diagramBlocks?.count ?? 0)")
        guard result != text || diagramBlocks != nil else { return }

        // Rich-text apps read the HTML, which shows diagrams monospaced.
        let html = diagramBlocks.map { RichText.html($0, metrics: menloMetrics) }
        write(result, html: html, autoGenerated: false)
        if let diagramBlocks, let html {
            diagramCopy = DiagramCopy(
                plain: result, fenced: RichText.markdown(diagramBlocks, metrics: menloMetrics), html: html,
                notesHTML: RichText.html(diagramBlocks, metrics: notesMetrics),
                variant: .original, changeCount: pasteboard.changeCount)
        }
    }

    /// Plain-text chat apps (Messenger, Slack, …) draw text in a proportional
    /// font, so they get diagrams fenced as ``` code blocks; Notes gets its own
    /// HTML; terminals and editors get the text exactly as copied.
    private func adapt(to bundleIdentifier: String?) {
        guard var copy = diagramCopy, pasteboard.changeCount == copy.changeCount,
              bundleIdentifier != Bundle.main.bundleIdentifier
        else { return }

        let variant = DiagramVariant.for(bundleIdentifier)
        guard variant != copy.variant else { return }
        log.info("switched to \(bundleIdentifier ?? "nil", privacy: .public): now \(String(describing: variant), privacy: .public)")

        // Marked auto-generated so clipboard history apps don't log each swap.
        let contents = copy.contents(for: variant)
        write(contents.string, html: contents.html, autoGenerated: true)
        copy.variant = variant
        copy.changeCount = pasteboard.changeCount
        diagramCopy = copy
    }

    private func write(_ string: String, html: String?, autoGenerated: Bool) {
        pasteboard.clearContents()
        pasteboard.setString(string, forType: .string)
        if let html { pasteboard.setString(html, forType: .html) }
        if autoGenerated { pasteboard.setData(Data(), forType: Self.autoGeneratedType) }
        // Our own write bumps changeCount; don't treat it as a new copy.
        lastChangeCount = pasteboard.changeCount
    }
}
